def design_values(m, lc) -> dict:
    im, P = m.get("impls", {}), m.get("parsers", {})
    r, q = im.get("rules", {}), im.get("llm_query", {})
    rh, lh = P.get("rule", {}).get("heldout20", {}), P.get("llm", {}).get("heldout20", {})
    if ran(lh):
        extract = (f"Rules alone: held-out {rh.get('overall_correct')}/20 with a silent wrong field (H07) on unseen "
                   f"phrasing. LLM extraction behind the validator: held-out {lh['overall_correct']}/20, unsafe guesses "
                   f"{lh['guessed_when_should_ask']}, wrong field values {lh['wrong_field_values']}, "
                   f"{usd(lh.get('cost_per_1000_usd'))} per 1,000. The hybrid keeps the LLM's coverage of free phrasing; "
                   f"the validator and the rule cross-check stop confident errors.")
        cost_line = (f"at the measured {usd(lh.get('cost_per_1000_usd'))} per 1,000 extractions, 100,000 users × 2 "
                     f"requests ≈ {usd(lh.get('cost_per_1000_usd', 0) * 200)}.")
    else:
        extract = (f"Rules alone: held-out {rh.get('overall_correct')}/20 with a silent wrong field (H07): regexes do not "
                   f"generalise to new wording. The LLM extractor adds coverage, but only behind the rule validator; its "
                   f"measured figures appear in the parser table once the run has a Gemini key.")
        cost_line = ("not measured in this run. Estimate at Gemini 2.5 Flash list price ($0.30 / $2.50 per million "
                     "input / output tokens): ~1,000 input and ~300 output tokens per extraction ≈ $0.001, so 100,000 "
                     "users × 2 requests ≈ $210 (thinking tokens can raise output; the measured run replaces this).")
    compute = (f"{r.get('correct')}/{r.get('n')} rupee-exact, 100% of answers traceable to clauses, identical on 10/10 "
               f"repeats, {num(r.get('latency_ms_p50'), 2)} ms, no API cost.")
    if ran(q):
        compute += (f" The LLM-at-query-time alternative scored {q['correct']}/{q['n']} on its sample at "
                    f"{usd(q['cost_per_1000_usd'])} per 1,000 requests and {num(q['latency_ms_p50'])} ms.")
        st = lc.get("llm", {}).get("stale_text") if ran(lc.get("llm")) else None
        query = (f"Measured {q['correct']}/{q['n']} rupee-exact (sample), deterministic across 10 runs: "
                 f"{'yes' if q['deterministic'] else 'no'}, traceable {pc(q['traceable'])}, {usd(q['cost_per_1000_usd'])} "
                 f"per 1,000, p50 {num(q['latency_ms_p50'])} ms. Anything short of 100% fails \"correct to the rupee\", a "
                 f"{q['n']}-case sample cannot prove 100% even when it scores 100%, answers are not guaranteed to repeat, "
                 f"and cost grows with every user."
                 + (f" Given last year's rule text it answered FY 2025-26 requests with {st['wrong_silent']}/{st['n']} "
                    f"silently wrong results and {st['loud_errors']} errors." if st else ""))
    else:
        query = ("Not measured in this run (no key). Structurally it cannot meet the bar: every answer depends on a "
                 "sampled model, cost scales with users, and a stale rule text produces a confident answer rather than "
                 "an error (Task 5). The table above shows its measured figures once run with a key.")
    return {"extract_why": extract, "compute_why": compute, "query_why": query, "cost_line": cost_line,
            "rules_lines": lc.get("edit_size", {}).get("rules", {}).get("config_lines_changed", "?"),
            "rules_ms": num(r.get("latency_ms_p50"), 2), "rule_heldout": rh.get("overall_correct", "?")}


