"""Render RESULTS_A.md, RESULTS_B.md and DECISION_MATRIX.md from results/*.json. Every number in those files
comes from a run; the prose around them is fixed. Re-run `python run_all.py` to regenerate."""
from __future__ import annotations

import json
import time
from pathlib import Path

ROOT = Path(__file__).parent
R = ROOT / "results"


def j(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else {}


def pc(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def num(x, d=0):
    if x is None:
        return "n/a"
    if not isinstance(x, (int, float)):
        return str(x)
    return f"{x:,.{d}f}"


def usd(x):
    if x is None:
        return "n/a"
    return f"${x:,.4f}" if x < 1 else f"${x:,.2f}"


def ran(d):
    return isinstance(d, dict) and "status" not in d and d


def banner_llm(status):
    if status.startswith("offline (cache entries: 0)"):
        return ("> **LLM columns not measured in this run** (no `GEMINI_API_KEY`, empty cache). Run "
                "`GEMINI_API_KEY=... python run_all.py` once; responses are cached in `.llm_cache/` so later runs "
                "reproduce the same numbers for free.\n")
    return ""


