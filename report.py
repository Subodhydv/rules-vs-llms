def scale_fmt(sc: dict) -> dict:
    out = {}
    for k, v in sc.items():
        if not isinstance(v, (int, float)):
            out[k] = v
        elif "share" in k:
            out[k] = pc(v, 2)
        elif k == "llm_usd_per_row":
            out[k] = f"{v:.7f}"
        elif "calls" in k or k.startswith("rows") or "rows_per_sec" in k or k == "customers":
            out[k] = num(v)
        else:
            out[k] = num(v, 2)
    return out


